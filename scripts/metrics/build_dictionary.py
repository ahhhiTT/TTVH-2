"""Generate src/lib/metric-dictionary.ts from the Director's metric file (FILE INPUT FOR AI REPORT).

    python3 -m pip install openpyxl
    python3 scripts/metrics/build_dictionary.py [path/to/FILE_INPUT.xlsx]

Default input: docs/report-inputs/FILE_INPUT_FOR_AI_REPORT_da_cap_nhat.xlsx (gitignored).
Only the sheet "Định nghĩa chỉ số" is read: metric names, definitions, formulas and source
columns. No brand figures. Re-run whenever the Director updates the file.
"""
import json
import os
import sys
import unicodedata

import openpyxl

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "docs", "report-inputs", "FILE_INPUT_FOR_AI_REPORT_da_cap_nhat.xlsx")
OUT = os.path.join(ROOT, "src", "lib", "metric-dictionary.ts")


def text(v):
    if v is None:
        return ""
    s = unicodedata.normalize("NFC", str(v)).strip()
    # plain copy: no em/en dashes in UI text
    return s.replace("—", "-").replace("–", "-")


wb = openpyxl.load_workbook(SRC, data_only=True)
ws = wb["Định nghĩa chỉ số"]
rows = []
section = ""
for r in range(2, ws.max_row + 1):
    code = text(ws.cell(r, 1).value)
    part = text(ws.cell(r, 2).value)
    group = text(ws.cell(r, 3).value)
    if not code:
        if part:
            section = f"{part} {group}".strip()
        continue
    note = text(ws.cell(r, 12).value)
    confirmed = text(ws.cell(r, 10).value)
    unsure = "chưa chắc chắn" in note.lower() or "cần xác nhận" in note.lower()
    rows.append({
        "code": code,
        "section": section,
        "group": group,
        "name": text(ws.cell(r, 4).value),
        "unit": text(ws.cell(r, 5).value),
        "templateFormula": text(ws.cell(r, 6).value),
        "rollUp": text(ws.cell(r, 7).value),
        "source": text(ws.cell(r, 8).value),
        "definition": text(ws.cell(r, 9).value),
        "formula": confirmed,
        "rawColumn": text(ws.cell(r, 11).value),
        "note": note,
        "status": "confirmed" if confirmed and not unsure else "tbd",
    })

body = json.dumps(rows, ensure_ascii=False, indent=2)
with open(OUT, "w", encoding="utf-8") as f:
    f.write(
        "// GENERATED by scripts/metrics/build_dictionary.py from the Director's metric file.\n"
        "// Do not edit by hand; update the Excel file and re-run the script.\n"
        "// Content is in Vietnamese (source language of the file).\n\n"
        "export interface MetricEntry {\n"
        "  code: string;\n  section: string;\n  group: string;\n  name: string;\n  unit: string;\n"
        "  templateFormula: string;\n  rollUp: string;\n  source: string;\n  definition: string;\n"
        "  formula: string; // confirmed formula, empty when not confirmed\n"
        "  rawColumn: string;\n  note: string;\n  status: \"confirmed\" | \"tbd\";\n}\n\n"
        f"export const METRIC_DICTIONARY: MetricEntry[] = {body};\n"
    )
print(f"{len(rows)} metrics -> {OUT}")
